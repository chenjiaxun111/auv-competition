#!/usr/bin/env python3
"""Build a YOLO11-Pose dataset from reviewed four-corner annotations."""

from __future__ import annotations

import argparse
import os
import shutil
from pathlib import Path


HERE = Path(__file__).resolve().parent
SOURCE_IMAGES = HERE / "all_yolo11_dataset" / "images"
SOURCE_LABELS = HERE / "gate_pose_annotations" / "labels"
DEFAULT_OUTPUT = HERE / "gate_pose_yolo11_dataset"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--force", action="store_true")
    return parser.parse_args()


def validate_label(path: Path) -> int:
    count = 0
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        fields = line.split()
        if len(fields) != 17 or fields[0] != "0":
            raise ValueError(f"{path}:{line_number}: expected class plus box and 4x(x,y,v)")
        values = list(map(float, fields[1:]))
        if not all(0 <= value <= 1 for value in values[:4]):
            raise ValueError(f"{path}:{line_number}: box outside normalized range")
        for offset in range(4, 16, 3):
            x, y, visibility = values[offset : offset + 3]
            if not (0 <= x <= 1 and 0 <= y <= 1 and visibility == 2):
                raise ValueError(f"{path}:{line_number}: invalid visible keypoint")
        count += 1
    if count == 0:
        raise ValueError(f"empty pose label: {path}")
    return count


def main() -> int:
    args = parse_args()
    output = args.output.resolve()
    records: dict[str, list[tuple[Path, Path, int]]] = {"train": [], "val": []}
    for split in records:
        label_dir = SOURCE_LABELS / split
        for label in sorted(label_dir.glob("*.txt")) if label_dir.is_dir() else []:
            image = SOURCE_IMAGES / split / f"{label.stem}.jpg"
            if not image.is_file():
                raise SystemExit(f"缺少图片: {image}")
            records[split].append((image, label, validate_label(label)))
    if not records["train"] or not records["val"]:
        raise SystemExit("train和val都至少需要一张已完成的Pose标注")

    if output.exists():
        if not args.force:
            raise SystemExit(f"输出目录已存在: {output}\n重建请加 --force")
        shutil.rmtree(output)
    for split in records:
        (output / "images" / split).mkdir(parents=True)
        (output / "labels" / split).mkdir(parents=True)
        for image, label, _count in records[split]:
            os.symlink(image.resolve(), output / "images" / split / image.name)
            shutil.copy2(label, output / "labels" / split / label.name)

    (output / "data.yaml").write_text(
        f"""# Generated by prepare_gate_pose_dataset.py
path: {output.as_posix()}
train: images/train
val: images/val

kpt_shape: [4, 3]
flip_idx: [1, 0, 3, 2]

names:
  0: gate
""",
        encoding="utf-8",
    )
    for split, items in records.items():
        print(f"{split.upper()}_IMAGES={len(items)}")
        print(f"{split.upper()}_GATES={sum(item[2] for item in items)}")
    print(f"DATASET={output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
